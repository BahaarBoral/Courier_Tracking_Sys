-- Sequences in Oracle are database objects that generate numeric sequences.
-- They are often used to create unique values for primary key columns, avoiding 
-- concurrency issues and the need for application-level ID generation.

CREATE SEQUENCE SEQ_CUSTOMER START WITH 1000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_EMPLOYEE START WITH 2000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_WAREHOUSE START WITH 3000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_VEHICLE START WITH 4000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_ROUTE START WITH 5000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_SHIPMENT START WITH 10000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_PARCEL START WITH 20000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TRACKING START WITH 30000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DELIVERY START WITH 40000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_PAYMENT START WITH 50000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_ACCOUNT START WITH 60000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_HISTORY START WITH 70000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_AUDIT START WITH 80000 INCREMENT BY 1 NOCACHE NOCYCLE;
